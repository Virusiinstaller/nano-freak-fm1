"""Regenerate firmware/src/eng_nano_tables.h: the WAVESHAPER tables of the NANO engine, taken from the Nano Freak test bed's
nf_tables.c (tables of Mutable Instruments Plaits, Emilie Gillet, MIT). Usage: gen_nano_tables.py path/to/nano-freak/dsp/nf_tables.c"""
import re, sys
src = open(sys.argv[1]).read()
def arr(name):
    m = re.search(name + r'\[\d+\] = \{(.*?)\};', src, re.S)
    return [float(x.replace('f', '')) for x in m.group(1).replace('\n', ' ').split(',') if x.strip()]
def rows(a, n=12):
    return ",\n    ".join(", ".join(str(x) for x in a[i:i + n]) for i in range(0, len(a), n))
out = ["/* SPDX-License-Identifier: GPL-3.0-only */",
       "/* Generated by tools/gen_nano_tables.py from the Nano Freak test bed (Plaits tables, Emilie Gillet, MIT). Do not edit. */"]
ws = ["inverse_tan", "inverse_sin", "linear", "bump", "double_bump"]
out.append("/* the five waveshaper transfer curves, 257 points each (the last repeats), Q15 as Plaits stores them */")
out.append("static const int16_t NANO_WS[5][257] = {")
for n in ws:
    out.append("  {\n    " + rows([int(x) for x in arr("nf_lut_ws_" + n)]) + "\n  },")
out.append("};")
fold = arr("nf_lut_fold")[1:514]                      # 512 points and one more, without the guard sample before
q = [max(-32768, min(32767, round(x * 32768))) for x in fold]
out.append("/* the wavefolder, 513 points, Q15 */")
out.append("static const int16_t NANO_FOLD[513] = {\n    " + rows(q) + "\n};")
open("firmware/src/eng_nano_tables.h", "w").write("\n".join(out) + "\n")
